# Программа выводит сумму квадратов чисел от 1 до n включительно. В программе три ошибки.
# Исправьте их.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     3
#   в терминале:
#     Число n: 3
#     Сумма квадратов: 14
# Пример 2
#   ввод:
#     1
#   в терминале:
#     Число n: 1
#     Сумма квадратов: 1
# Пример 3
#   ввод:
#     10
#   в терминале:
#     Число n: 10
#     Сумма квадратов: 385

# Решение: исправьте программу ниже
n = input("Число n: ")
for number in range(1, n):
    total = 0
    total += number * number
print("Сумма квадратов:", total)
