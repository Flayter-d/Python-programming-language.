# В магазине три кассы. Про каждую вводится ответ, открыта ли она: «да» или «нет». Выведите, верно
# ли, что открыта ровно одна касса.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     нет
#     да
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): нет
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): нет
#     True
# Пример 2
#   ввод:
#     да
#     да
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): да
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): нет
#     False
# Пример 3
#   ввод:
#     нет
#     нет
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): нет
#     Касса 2 открыта (да/нет): нет
#     Касса 3 открыта (да/нет): нет
#     False
# Пример 4
#   ввод:
#     да
#     да
#     да
#   в терминале:
#     Касса 1 открыта (да/нет): да
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): да
#     False

# Решение
cashier1 = input("Касса 1 открыта (да/нет): ")
cashier2 = input("Касса 2 открыта (да/нет): ") 
cashier3 = input("Касса 3 открыта (да/нет): ")

#Считаем, сколько касс открыто (сравниваем со строкой "да")
open_count = 0
if cashier1 == "да":
  open_count += 1 
  if cashier2 == "да":
    open_count += 1 
    if cashier3 == "да":
      open_count += 1

#Ровно одна касса открыта, если счётчик равен 1
exactly_one_open = open_count == 1 
print(exactly_one_open)
